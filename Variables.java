public class Variables {
    public static void main(String args[]) {
        int a = 5;
        int b = 7;
        int c = 5;
        System.out.println(a + b + c);
        System.out.println(a - b - c);
        System.out.println(a * b * c);
        System.out.println((double) (a + b) / c);
    }
}
